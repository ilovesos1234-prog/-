function numline(o) {
  const W = 230, H = 52, L = 12, R = W - 12, y = 30;
  const X = (v) => L + (v - o.x0) / (o.x1 - o.x0) * (R - L);
  let s = `<svg width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" font-family="Nanum Gothic" font-size="10">`;
  s += `<line x1="4" y1="${y}" x2="${W - 4}" y2="${y}" stroke="#222" stroke-width="1"/><path d="M${W - 4} ${y} l-6 -3 v6z" fill="#222"/><path d="M4 ${y} l6 -3 v6z" fill="#222"/>`;
  for (const t of o.ticks || []) s += `<line x1="${X(t.v)}" y1="${y - 3}" x2="${X(t.v)}" y2="${y + 3}" stroke="#222"/>${t.t !== undefined ? `<text x="${X(t.v)}" y="${y + 15}" text-anchor="middle">${t.t}</text>` : ''}`;
  for (const [a, b] of o.arcs || []) {
    const m = (X(a) + X(b)) / 2;
    s += `<path d="M${X(a)} ${y} Q${m} ${y - 18} ${X(b)} ${y}" fill="none" stroke="#666" stroke-width=".8"/><text x="${m}" y="${y - 7}" text-anchor="middle" font-size="7">//</text>`;
  }
  for (const p of o.pts || []) s += `<circle cx="${X(p.v)}" cy="${y}" r="2.3" fill="#111"/><text x="${X(p.v)}" y="${p.up ? y - 9 : y + 15}" text-anchor="middle">${p.t}</text>`;
  return s + '</svg>';
}

